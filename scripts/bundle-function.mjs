// Joins notify-rsvp/email.ts + index.ts into ONE file you can paste into the
// Supabase dashboard editor (Edge Functions > Deploy a new function > Via Editor).
// Run after changing either file:  node scripts/bundle-function.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'functions', 'notify-rsvp');
const email = readFileSync(join(dir, 'email.ts'), 'utf8').replace(/^export /gm, '');
const index = readFileSync(join(dir, 'index.ts'), 'utf8').replace(/^import .* from '\.\/email\.ts';\n/m, '');
writeFileSync(join(dir, 'paste-into-dashboard.ts'),
  '// GENERATED by scripts/bundle-function.mjs from email.ts + index.ts. Do not edit by hand.\n' +
  '// Paste ALL of this into the Supabase dashboard function editor.\n\n' + email + '\n' + index);
console.log('wrote supabase/functions/notify-rsvp/paste-into-dashboard.ts');
