// Build step for Vercel (no dependencies, plain Node 18+).
//
//   1. Copies site/ -> public/ (only public/ is deployed, so docs, SQL and
//      scripts are never served).
//   2. Writes public/config.js from environment variables:
//        SUPABASE_URL       e.g. https://abcd1234.supabase.co
//        SUPABASE_ANON_KEY  the public anon / publishable key
//   3. Refuses to build if the key looks like a secret (service_role or
//      sb_secret_), or if vercel.json's CSP does not allow SUPABASE_URL.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Usage: node scripts/build.mjs [sourceDir] [vercelJson] [outDir]
//   public site (default): site        vercel.json        public
//   admin site:            admin/site  admin/vercel.json  admin/public
const [srcRel = 'site', vercelRel = 'vercel.json', outRel = 'public'] = process.argv.slice(2);
const out = join(root, outRel);

function fail(msg) {
  console.error(`\nBuild stopped: ${msg}\n`);
  process.exit(1);
}

const url = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (process.env.SUPABASE_ANON_KEY || '').trim();

if (!url) fail('SUPABASE_URL is not set. Add it in Vercel > Project > Settings > Environment Variables.');
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) fail('SUPABASE_URL must look like https://<project-ref>.supabase.co');
if (!key) fail('SUPABASE_ANON_KEY is not set. Add it in Vercel > Project > Settings > Environment Variables.');

// --- never ship a secret key to the browser ---------------------------------
if (key.startsWith('sb_secret_')) fail('SUPABASE_ANON_KEY is a SECRET key (sb_secret_...). Use the publishable/anon key.');
const parts = key.split('.');
if (parts.length === 3) {
  let role = '';
  try {
    role = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8')).role;
  } catch {
    fail('SUPABASE_ANON_KEY looks like a JWT but could not be read.');
  }
  if (role !== 'anon') fail(`SUPABASE_ANON_KEY has role "${role}". Only the anon key may be used in the page.`);
} else if (!key.startsWith('sb_publishable_')) {
  fail('SUPABASE_ANON_KEY is not an anon JWT or an sb_publishable_ key.');
}

// --- CSP must allow exactly this Supabase project ----------------------------
const vercel = JSON.parse(readFileSync(join(root, vercelRel), 'utf8'));
const csp = (vercel.headers || [])
  .flatMap((h) => h.headers || [])
  .find((h) => h.key.toLowerCase() === 'content-security-policy');
if (!csp) fail('vercel.json has no Content-Security-Policy header.');
const connect = (csp.value.match(/connect-src ([^;]+)/) || [])[1] || '';
if (!connect.split(/\s+/).includes(url)) {
  fail(`${vercelRel} CSP connect-src does not include ${url}. Put your Supabase Project URL in vercel.json connect-src.`);
}

// --- output -------------------------------------------------------------------
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(root, srcRel), out, { recursive: true });
writeFileSync(
  join(out, 'config.js'),
  '// Generated by scripts/build.mjs. Public values only. Do not edit or commit.\n' +
    `window.MIVA_CONFIG = Object.freeze(${JSON.stringify({ supabaseUrl: url, anonKey: key })});\n`
);
console.log(`Built ${outRel}/ from ${srcRel}/ for ${url}`);
